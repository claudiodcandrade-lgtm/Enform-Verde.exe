#!/usr/bin/env python3
"""Validate documentation synchronization in commit order.

Binary Word updates may be generated by a workflow after the substantive change.
All required documents must be updated at or after the latest effective change.
Documentation from before that change cannot satisfy the release gate.
"""
import subprocess
import sys
from pathlib import Path

SPEC = "docs/ESPECIFICACAO_TECNICA_COMPLETA.docx"
PROMPT = "docs/PROMPT_CONTINUIDADE_ENFORM_VERDE_2026-11-04_v52.md"
HISTORICAL_PROMPT = "docs/PROMPT_CONTINUIDADE_ENFORM_VERDE_2026-10-27_v43.md"
SOIL_SPEC = "docs/ESPECIFICACAO_SOLO_PRONASOLOS_0_100_2026-10-28.md"
SYNC = ".github/workflows/sync-full-spec-word.yml"

def effective(path):
    if path in (SPEC,PROMPT) or path.startswith("docs/"):
        return False
    return path.endswith((".py",".yml",".yaml",".csv",".gz",".json",".txt")) or path.startswith(".github/")

def check(changed, *, workflow_text=None, word_exists=None):
    eff=sorted(p for p in changed if effective(p))
    if not eff:return eff,[]
    missing=[]
    if PROMPT not in changed:missing.append(PROMPT)
    if HISTORICAL_PROMPT not in changed:missing.append(HISTORICAL_PROMPT)
    if SOIL_SPEC not in changed:missing.append(SOIL_SPEC)
    if SPEC not in changed:
        if workflow_text is None:
            workflow_text=Path(SYNC).read_text(encoding="utf-8") if Path(SYNC).exists() else ""
        if word_exists is None:
            word_exists=Path(SPEC).is_file()
        checkpoints=[p for p in changed if p.startswith("docs/spec_updates/") and p.endswith(".md")]
        active=bool(word_exists and checkpoints and any(
            ("- "+p) in workflow_text and ("--entry "+p) in workflow_text
            for p in checkpoints))
        if not active:
            missing.append(SPEC)  # stable return contract; diagnostics explain checkpoint alternative
    return eff,missing

def latest_change_window(commits):
    """Paths changed from the most recent effective commit through HEAD.

    Documentation is allowed in a subsequent commit (e.g. generated DOCX), but
    documentation predating the latest code change never satisfies that change.
    Each element is the set of paths changed in one commit, oldest first.
    """
    last_effective = None
    for index, paths in enumerate(commits):
        if any(effective(path) for path in paths):
            last_effective = index
    if last_effective is None:
        return set()
    return set().union(*commits[last_effective:])


def commit_paths(base, head):
    out = subprocess.run(
        ["git", "log", "--reverse", "--format=__ENFORM_COMMIT__%H",
         "--name-only", f"{base}..{head}"],
        capture_output=True, text=True, check=True,
    )
    commits = []
    for line in out.stdout.splitlines():
        if line.startswith("__ENFORM_COMMIT__"):
            commits.append(set())
        elif line.strip():
            if not commits:
                raise RuntimeError("Unexpected git log format")
            commits[-1].add(line.strip())
    return commits


def main(base, head):
    commits = commit_paths(base, head)
    changed = latest_change_window(commits)
    effective_files, missing = check(changed)
    print(f"Commits audited: {len(commits)}; latest effective change files: "
          f"{len(effective_files)}; docs missing: {missing or 'none'}")
    for item in missing:
        print(f"::error::{item}")
    return 1 if missing else 0

if __name__=="__main__":
    raise SystemExit(main(sys.argv[1],sys.argv[2]))
